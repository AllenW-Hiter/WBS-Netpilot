"""Bash switches for mutually exclusive terminal proxy sources."""
import shlex

from .proxy import proxy_environment

BASH_BEGIN = "# >>> NetPilot proxy profiles >>>"
BASH_END = "# <<< NetPilot proxy profiles <<<"


def profile_script(source, proxy, helper):
    values = proxy_environment(proxy)
    assignments = "\n".join("  printf -v {} '%s' {}\n  export {}".format(k, shlex.quote(v), k) for k, v in values.items())
    call = shlex.join(helper)
    script = '''# Generated by NetPilot proxy profiles; may contain credentials; mode 0600.
# Source defines functions only. Never auto-enable at login.
if [[ "${_NETPILOT_CODEX_WRAPPER:-}" || "${_NETPILOT_PROXY_ACTIVE:-0}" == 1 ]]; then
  printf '请先关闭旧版代理开关或打开新的 Bash 终端，再加载新版函数。\\n' >&2
  return 1
fi
_netpilot_@SOURCE@_on() {
  local k declaration
  local keys=(http_proxy https_proxy all_proxy no_proxy HTTP_PROXY HTTPS_PROXY ALL_PROXY NO_PROXY)
  if [[ -n "${_NETPILOT_PROFILE_ACTIVE:-}" && "$_NETPILOT_PROFILE_ACTIVE" != @SOURCE@ ]]; then
    printf '当前终端已有 %s 代理，请先运行对应的 _proxy_off。\\n' "$_NETPILOT_PROFILE_ACTIVE" >&2
    return 1
  fi
  for k in "${keys[@]}"; do
    declaration="$(declare -p "$k" 2>/dev/null || true)"
    if [[ "$declaration" =~ ^declare\\ -[^[:space:]]*r ]]; then
      printf '代理变量 %s 为只读；未继续切换。\\n' "$k" >&2
      return 1
    fi
  done
  command @HELPER@ proxy-session-on @SOURCE@ || return 1
  if [[ -z "${_NETPILOT_PROFILE_ACTIVE:-}" ]]; then
    declare -gA _NETPILOT_PROFILE_VALUE=() _NETPILOT_PROFILE_SET=() _NETPILOT_PROFILE_EXPORT=()
    for k in "${keys[@]}"; do
      if [[ -v "$k" ]]; then
        _NETPILOT_PROFILE_SET["$k"]=1
        _NETPILOT_PROFILE_VALUE["$k"]="${!k}"
      else
        _NETPILOT_PROFILE_SET["$k"]=0
      fi
      declaration="$(declare -p "$k" 2>/dev/null || true)"
      if [[ "$declaration" =~ ^declare\\ -[^[:space:]]*x ]]; then
        _NETPILOT_PROFILE_EXPORT["$k"]=1
      else
        _NETPILOT_PROFILE_EXPORT["$k"]=0
      fi
    done
  fi
@ASSIGNMENTS@
  declare -g _NETPILOT_PROFILE_ACTIVE=@SOURCE@
  printf '@SOURCE@ 终端代理已开启；APT/Git 按保存的选项联动。\\n'
}
_netpilot_@SOURCE@_off() {
  local k declaration
  local keys=(http_proxy https_proxy all_proxy no_proxy HTTP_PROXY HTTPS_PROXY ALL_PROXY NO_PROXY)
  if [[ -n "${_NETPILOT_PROFILE_ACTIVE:-}" && "$_NETPILOT_PROFILE_ACTIVE" != @SOURCE@ ]]; then
    printf '当前终端的代理来源不同；未撤销其他来源。\\n' >&2
    return 1
  fi
  if [[ -n "${_NETPILOT_PROFILE_ACTIVE:-}" ]]; then
    for k in "${keys[@]}"; do
      declaration="$(declare -p "$k" 2>/dev/null || true)"
      if [[ "$declaration" =~ ^declare\\ -[^[:space:]]*r ]]; then
        printf '代理变量 %s 为只读；未继续关闭。\\n' "$k" >&2
        return 1
      fi
    done
  fi
  command @HELPER@ proxy-session-off @SOURCE@ || return 1
  [[ -n "${_NETPILOT_PROFILE_ACTIVE:-}" ]] || return 0
  for k in "${keys[@]}"; do
    if [[ "${_NETPILOT_PROFILE_SET[$k]:-0}" == 1 ]]; then
      printf -v "$k" '%s' "${_NETPILOT_PROFILE_VALUE[$k]}"
      if [[ "${_NETPILOT_PROFILE_EXPORT[$k]:-0}" == 1 ]]; then export "$k"; else export -n "$k"; fi
    else
      unset "$k"
    fi
  done
  unset _NETPILOT_PROFILE_ACTIVE _NETPILOT_PROFILE_VALUE _NETPILOT_PROFILE_SET _NETPILOT_PROFILE_EXPORT
  printf '@SOURCE@ 终端代理已关闭，已恢复启用前的变量；已有进程需另行退出。\\n'
}
if ! declare -F @SOURCE@_proxy_on >/dev/null; then
  @SOURCE@_proxy_on() { _netpilot_@SOURCE@_on; }
fi
if ! declare -F @SOURCE@_proxy_off >/dev/null; then
  @SOURCE@_proxy_off() { _netpilot_@SOURCE@_off; }
fi
'''
    return script.replace("@SOURCE@", source).replace("@HELPER@", call).replace("@ASSIGNMENTS@", assignments)
