            {"配置/更新": self.configure, "测试当前代理": self.test,
             "安装/更新终端代理开关函数": self.install_bash_loader,
             "清理旧 APT / Git 代理配置": self.cleanup_legacy,
             "移除本用户代理配置": self.remove,
             "配置当前用户 GitHub SSH 密钥": lambda: GitHubSSH().configure()}[item]()
