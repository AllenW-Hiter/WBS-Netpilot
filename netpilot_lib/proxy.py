APT_FILE = pathlib.Path("/etc/apt/apt.conf.d/99-netpilot-proxy")
APT_MARKER = "// Managed by NetPilot; remove only this file to stop the override.\n"
APT_MAIN = pathlib.Path("/etc/apt/apt.conf")
GIT_PROXY_PATTERN = r"^(http(\..*)?\.proxy|remote\..*\.proxy|core\.gitproxy)$"
BASH_BEGIN = "# >>> NetPilot proxy functions >>>"
BASH_END = "# <<< NetPilot proxy functions <<<"
APT_HELPER = ["sudo", "--", "/usr/bin/python3",
              str(pathlib.Path(__file__).resolve().parents[1] / "netpilot.py")]


def proxy_url(scheme: str, host: str, port: int, username: str = "", password: str = "") -> str:
    if scheme not in ("http", "https", "socks5h"):
        raise UserError("代理协议必须为 http/https/socks5h。")
    if isinstance(port, bool) or not isinstance(port, int) or not 1 <= port <= 65535:
        raise UserError("代理端口必须为 1～65535。")
    host = host.strip().strip("[]")
    if not host or any(ord(c) < 33 for c in host):
        raise UserError("代理主机地址无效。")
    try:
        addr = ipaddress.ip_address(host)
        host = "[{}]".format(addr) if addr.version == 6 else str(addr)
    except ValueError:
        try:
            host = host.encode("idna").decode("ascii")
        except UnicodeError:
            raise UserError("代理主机名无效。")
        if len(host) > 253 or not all(re.fullmatch(r"[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?", x)
                                      for x in host.rstrip(".").split(".")):
            raise UserError("代理主机必须是合法的 IP 或域名，不能包含协议、路径或端口。")
    if any(ord(c) < 32 for c in username + password):
        raise UserError("代理认证信息不能包含控制字符。")
    if password and not username:
        raise UserError("填写密码时也需填写用户名。")
    auth = ""
    if username:
        auth = urllib.parse.quote(username, safe="") + ":" + urllib.parse.quote(password, safe="") + "@"
    return "{}://{}{}:{}".format(scheme, auth, host, port)


def validate_proxy_config(config):
    if not isinstance(config, dict) or config.get("schema") != 1:
        raise UserError("代理配置格式错误。")
    allowed = {"schema", "scheme", "host", "port", "username", "password", "no_proxy"}
    if set(config) - allowed:
        raise UserError("代理配置包含未知字段。")
    url = proxy_url(config.get("scheme", ""), config.get("host", ""), config.get("port", 0),
                    config.get("username", ""), config.get("password", ""))
    no_proxy = config.get("no_proxy", "localhost,127.0.0.1,::1")
    if not isinstance(no_proxy, str) or any(ord(c) < 32 for c in no_proxy):
        raise UserError("no_proxy 格式错误。")
    return url


def proxy_environment(config):
    url = validate_proxy_config(config)
    no_proxy = config.get("no_proxy", "localhost,127.0.0.1,::1")
    return {"http_proxy": url, "https_proxy": url, "all_proxy": url,
            "HTTP_PROXY": url, "HTTPS_PROXY": url, "ALL_PROXY": url,
            "no_proxy": no_proxy, "NO_PROXY": no_proxy}


def bash_proxy_script(config, apt_helper=None):
    values = proxy_environment(config)
    assignments = "\n".join("  printf -v {} '%s' {}\n  export {}".format(k, shlex.quote(v), k)
                            for k, v in values.items())
    helper = shlex.join(APT_HELPER if apt_helper is None else apt_helper)
    # Source defines functions only; it does NOT activate proxy automatically.
    return '''# Generated by NetPilot. Contains proxy credentials; keep mode 0600.
# Bash only. Source this file, then run netpilot_proxy_on / netpilot_proxy_off.
_netpilot_proxy_on() {
  local k declaration
  local keys=(http_proxy https_proxy all_proxy no_proxy HTTP_PROXY HTTPS_PROXY ALL_PROXY NO_PROXY)
  for k in "${keys[@]}"; do
    declaration="$(declare -p "$k" 2>/dev/null || true)"
    if [[ "$declaration" =~ ^declare\\ -[^[:space:]]*r ]]; then
      printf '代理变量 %s 为只读；未修改任何变量。\\n' "$k" >&2
      return 1
    fi
  done
''' + '  command ' + helper + ''' proxy-apt-on || {
    printf 'APT 代理未能启用；本终端代理变量未改变。\\n' >&2
    return 1
  }
''' + '''
  if [[ "${_NETPILOT_PROXY_ACTIVE:-0}" != 1 ]]; then
    declare -gA _NETPILOT_PROXY_SAVED_VALUE=()
    declare -gA _NETPILOT_PROXY_SAVED_SET=()
    declare -gA _NETPILOT_PROXY_SAVED_EXPORT=()
    for k in "${keys[@]}"; do
      if [[ -v "$k" ]]; then
        _NETPILOT_PROXY_SAVED_SET["$k"]=1
        _NETPILOT_PROXY_SAVED_VALUE["$k"]="${!k}"
      else
        _NETPILOT_PROXY_SAVED_SET["$k"]=0
      fi
      declaration="$(declare -p "$k" 2>/dev/null || true)"
      if [[ "$declaration" =~ ^declare\\ -[^[:space:]]*x ]]; then
        _NETPILOT_PROXY_SAVED_EXPORT["$k"]=1
      else
        _NETPILOT_PROXY_SAVED_EXPORT["$k"]=0
      fi
    done
  fi
''' + assignments + '''
  declare -g _NETPILOT_PROXY_ACTIVE=1
  printf 'APT 代理和本终端应用代理已启用；Git HTTPS、curl 等可使用代理。\\n'
}
_netpilot_proxy_off() {
  local k declaration
  if [[ "${_NETPILOT_PROXY_ACTIVE:-0}" == 1 ]]; then
    for k in http_proxy https_proxy all_proxy no_proxy HTTP_PROXY HTTPS_PROXY ALL_PROXY NO_PROXY; do
      declaration="$(declare -p "$k" 2>/dev/null || true)"
      if [[ "$declaration" =~ ^declare\\ -[^[:space:]]*r ]]; then
        printf '代理变量 %s 为只读；未关闭代理。\\n' "$k" >&2
        return 1
      fi
    done
  fi
''' + '  command ' + helper + ''' proxy-apt-off || {
    printf 'APT 代理未能关闭；本终端代理变量未改变。\\n' >&2
    return 1
  }
  [[ "${_NETPILOT_PROXY_ACTIVE:-0}" == 1 ]] || { printf 'APT 代理已关闭；本终端未由 NetPilot 启用代理。\\n'; return 0; }
  for k in http_proxy https_proxy all_proxy no_proxy HTTP_PROXY HTTPS_PROXY ALL_PROXY NO_PROXY; do
    if [[ "${_NETPILOT_PROXY_SAVED_SET[$k]:-0}" == 1 ]]; then
      printf -v "$k" '%s' "${_NETPILOT_PROXY_SAVED_VALUE[$k]}"
      if [[ "${_NETPILOT_PROXY_SAVED_EXPORT[$k]:-0}" == 1 ]]; then export "$k"; else export -n "$k"; fi
    else
      unset "$k"
    fi
  done
  unset _NETPILOT_PROXY_ACTIVE _NETPILOT_PROXY_SAVED_VALUE _NETPILOT_PROXY_SAVED_SET _NETPILOT_PROXY_SAVED_EXPORT
  printf 'APT 代理已关闭；已恢复本终端启用前的代理变量。\\n'
}
if ! declare -F netpilot_proxy_on >/dev/null; then
  netpilot_proxy_on() { _netpilot_proxy_on; }
fi
if ! declare -F netpilot_proxy_off >/dev/null; then
  netpilot_proxy_off() { _netpilot_proxy_off; }
fi
'''


def apt_text(config):
    url = validate_proxy_config(config)
    escaped = url.replace("\\", "\\\\").replace('"', '\\"')
    return APT_MARKER + 'Acquire::http::Proxy "{}";\nAcquire::https::Proxy "{}";\n'.format(escaped, escaped)


def without_apt_proxies(text):
    """Remove complete flat proxy directives; never guess at nested APT syntax."""
    retained = []
    removed = 0
    for line in text.splitlines(keepends=True):
        stripped = line.strip()
        if not stripped or stripped.startswith(("//", "#")):
            retained.append(line)
            continue
        if re.fullmatch(r'[^\s";{}]*::Proxy(?:[^\s";{}]*)\s+"(?:[^"\\]|\\.)*";\s*(?://.*)?',
                        stripped, re.I):
            removed += 1
        elif re.search(r"\b(?:Proxy|Proxy-Auto-Detect|ProxyAutoDetect)\b", stripped, re.I):
            raise UserError("发现非单行 APT 代理配置；请先人工整理该文件，未猜测删除范围。")
        else:
            retained.append(line)
    updated = "".join(retained)
    only_comments = all(not line.strip() or line.lstrip().startswith(("//", "#"))
                        for line in updated.splitlines())
    return ("" if only_comments else updated), removed


class ProxyManager:
    def __init__(self):
        self.account = operator_account()
        self.directory = pathlib.Path(self.account.pw_dir) / ".config" / "netpilot"
        self.config_file = self.directory / "proxy.json"
        self.shell_file = self.directory / "proxy.sh"

    def load(self):
        with as_operator():
            if not self.config_file.exists():
                raise UserError("尚未配置本用户的代理。")
            if self.config_file.is_symlink() or self.config_file.stat().st_mode & 0o077:
                raise UserError("代理配置必须是普通私有文件（chmod 600），不能是符号链接。")
            config = load_json(self.config_file)
        validate_proxy_config(config)
        return config

    def configure(self):
        print("这是从机使用主机已有的应用代理端口，不是透明 VPN 或整机流量接管。")
        print("主机代理需监听下游地址，并只放行需要的客户端；本工具不会自动修改代理软件或开放防火墙。")
        scheme = choose("代理协议", ["http", "socks5h", "https"],
                        lambda v: {"http": "HTTP/HTTP CONNECT（常用）", "socks5h": "SOCKS5，域名由代理端解析", "https": "使用 TLS 连接代理服务器（不是指访问 HTTPS 网站）"}[v])
        host = ask("主机代理监听地址", "192.168.1.20")
        value = ask("代理端口（以代理软件实际配置为准）")
        if not value.isdigit():
            raise UserError("端口必须为整数。")
        username = ask("认证用户名；无需认证则直接回车")
        password = ask("认证密码", secret=True) if username else ""
        config = {"schema": 1, "scheme": scheme, "host": host, "port": int(value),
                  "username": username, "password": password,
                  "no_proxy": ask("不走代理的主机列表；兼容旧版程序时使用明确主机/IP而非 CIDR", "localhost,127.0.0.1,::1," + host)}
        url = validate_proxy_config(config)
        print("代理目标：{}://{}:{}，认证：{}".format(scheme, host, value, "有" if username else "无"))
        print("将安装 ~/.bashrc 中的开关函数，并备份清理旧 APT / 当前用户 Git 代理项。")
        if not confirm("保存配置并安装统一代理开关（私有文件可能含明文认证信息）？"):
            return
        self.cleanup_legacy(confirm_action=False)
        with as_operator():
            safe_directory(self.directory)
            if self.config_file.exists():
                atomic_write(self.directory / ("proxy.before-" + timestamp() + ".json"), self.config_file.read_text(encoding="utf-8"))
            save_json(self.config_file, config)
            atomic_write(self.shell_file, bash_proxy_script(config))
        self.install_bash_loader()
        print("配置和函数已保存。当前父终端尚未改变。执行：")
        print("  source ~/.bashrc")
        print("  netpilot_proxy_on")
        print("关闭 APT 和本终端代理：netpilot_proxy_off")
        if confirm("现在从本机通过此代理测试 HTTPS？"):
            if os.geteuid() == 0:
                ensure_packages(["curl", "ca-certificates"])
            print(json.dumps(https_test(proxy=url), ensure_ascii=False, indent=2))

    def install_bash_loader(self):
        config = self.load()
        target = pathlib.Path(self.account.pw_dir) / ".bashrc"
        with as_operator():
            if target.is_symlink():
                raise UserError("拒绝修改符号链接 ~/.bashrc。")
            text = target.read_text(encoding="utf-8") if target.exists() else ""
            text_without_block = self.bashrc_without_block(text)
            if target.exists():
                atomic_write(self.directory / ("bashrc.before-" + timestamp()), text)
            safe_directory(self.directory)
            atomic_write(self.shell_file, bash_proxy_script(config))
            path = shlex.quote(str(self.shell_file))
            block = ("\n" + BASH_BEGIN + "\n"
                     "netpilot_proxy_on() {\n"
                     "  . " + path + " || return\n"
                     "  _netpilot_proxy_on\n}\n"
                     "netpilot_proxy_off() {\n"
                     "  if ! declare -F _netpilot_proxy_off >/dev/null; then\n"
                     "    . " + path + " || return\n  fi\n"
                     "  _netpilot_proxy_off\n}\n" + BASH_END + "\n")
            atomic_write(target, text_without_block + block, 0o644)
        print("已在 ~/.bashrc 安装 netpilot_proxy_on / netpilot_proxy_off；新终端不自动设置代理环境变量。")

    @staticmethod
    def bashrc_without_block(text):
        if text.count(BASH_BEGIN) != text.count(BASH_END) or text.count(BASH_BEGIN) > 1:
            raise UserError("~/.bashrc 的 NetPilot 加载块重复或不完整；请人工检查。")
        pattern = r"(?m)^# >>> NetPilot proxy functions >>>\n.*?^# <<< NetPilot proxy functions <<<\n?"
        updated, count = re.subn(pattern, "", text, flags=re.S)
        if BASH_BEGIN in text and count != 1:
            raise UserError("~/.bashrc 的 NetPilot 加载块格式异常；未修改。")
        return updated

    @staticmethod
    def check_apt_proxy(expected=None):
        output = run(["apt-config", "dump"], sensitive=True).stdout
        items = {}
        for line in output.splitlines():
            match = re.fullmatch(r'([^\s]+)\s+"(.*)";', line)
            if match and re.search(r"::proxy", match[1], re.I):
                items[match[1].lower()] = match[2]
        wanted = {} if expected is None else {
            "acquire::http::proxy": expected, "acquire::https::proxy": expected}
        if items != wanted:
            raise UserError("APT 仍有其他代理规则或覆盖项；请运行代理菜单的“清理旧 APT / Git 代理配置”。未报告切换成功。")

    def set_apt(self, enabled):
        require_root()
        config = self.load() if enabled else None
        with file_lock(STATE / "proxy.lock"):
            if APT_FILE.is_symlink():
                raise UserError("拒绝修改符号链接 APT 配置。")
            previous = APT_FILE.read_text() if APT_FILE.exists() else None
            if previous is not None and not previous.startswith(APT_MARKER):
                raise UserError("目标 APT 文件不是本工具创建的；请先清理旧代理配置。")
            try:
                if enabled:
                    atomic_write(APT_FILE, apt_text(config))
                elif previous is not None:
                    APT_FILE.unlink()
                self.check_apt_proxy(validate_proxy_config(config) if enabled else None)
            except (UserError, OSError):
                try:
                    if previous is not None:
                        atomic_write(APT_FILE, previous)
                    elif APT_FILE.exists():
                        APT_FILE.unlink()
                except (UserError, OSError):
                    raise UserError("APT 切换失败且原文件恢复失败；请检查 APT 配置，未报告成功。")
                raise

    def cleanup_legacy(self, confirm_action=True):
        """Back up before clearing APT proxy directives and user-global Git proxies."""
        require_root()
        with file_lock(STATE / "proxy.lock"):
            changes = []
            paths = [APT_MAIN] + sorted(APT_FILE.parent.iterdir())
            for path in paths:
                if path != APT_MAIN and (not re.fullmatch(r"[A-Za-z0-9_.-]+", path.name)
                                        or path.suffix not in ("", ".conf")):
                    continue
                if path.is_symlink():
                    raise UserError("APT 配置含符号链接；未自动清理：" + str(path))
                if not path.is_file():
                    continue
                text = path.read_text(encoding="utf-8")
                try:
                    updated, count = without_apt_proxies(text)
                except UserError as exc:
                    raise UserError(str(path) + "：" + str(exc))
                if count:
                    changes.append((path, text, updated, path.stat().st_mode & 0o777))
            git_items = []
            with as_operator():
                git_env = {"HOME": self.account.pw_dir, "XDG_CONFIG_HOME": str(pathlib.Path(self.account.pw_dir) / ".config")}
                parts = []
                if shutil.which("git"):
                    result = run(["git", "config", "--global", "--includes", "--null", "--show-origin",
                                  "--name-only", "--get-regexp", GIT_PROXY_PATTERN], check=False,
                                 env=git_env, sensitive=True)
                    if result.returncode not in (0, 1):
                        raise UserError("无法读取当前用户 Git 代理配置；未开始清理。")
                    parts = result.stdout.rstrip("\0").split("\0") if result.stdout else []
                else:
                    print("本机未安装 Git，跳过 Git 配置清理。")
                if len(parts) % 2:
                    raise UserError("Git 配置来源格式异常；未开始清理。")
                for origin, key in zip(parts[::2], parts[1::2]):
                    if not origin.startswith("file:") or "@" in key:
                        raise UserError("Git 代理项来源或名称需要人工检查；未开始清理。")
                    path = pathlib.Path(origin[5:]).absolute()
                    if path.is_symlink() or not path.resolve().is_relative_to(pathlib.Path(self.account.pw_dir).resolve()):
                        raise UserError("Git 代理配置不在用户主目录普通文件中；未自动清理。")
                    if (path, key) not in git_items:
                        git_items.append((path, key))
            print("待清理：{} 个 APT 文件的代理项，{} 个当前用户 Git 代理项。".format(len(changes), len(git_items)))
            for path, _, _, _ in changes:
                print("  " + str(path))
            if confirm_action and not confirm("先私有备份，再清理这些旧代理项？"):
                return
            token = timestamp() + "-" + uuid.uuid4().hex[:8]
            apt_backup = STATE / "backups" / "proxy" / token
            git_backup = self.directory / ("legacy-proxy-" + token)
            if changes:
                safe_directory(apt_backup, root_only=True)
                for index, (path, text, _, _) in enumerate(changes):
                    atomic_write(apt_backup / (str(index) + "-" + path.name), text)
            with as_operator():
                if git_items:
                    safe_directory(git_backup)
                    for index, path in enumerate(dict.fromkeys(path for path, _ in git_items)):
                        atomic_write(git_backup / (str(index) + "-" + path.name), path.read_text(encoding="utf-8"))
            try:
                for path, _, updated, mode in changes:
                    if updated:
                        atomic_write(path, updated, mode)
                    else:
                        path.unlink()
                with as_operator():
                    for path, key in git_items:
                        run(["git", "config", "--file", str(path), "--unset-all", key],
                            env=git_env, sensitive=True)
                self.check_apt_proxy()
            except (UserError, OSError):
                raise UserError("旧代理清理未全部完成；备份保留于 {} 和 {}，请检查现状。".format(apt_backup, git_backup))
            print("旧 APT / 当前用户 Git 代理项已清理；其他 Git 配置保留。")
            if changes:
                print("APT 私有备份：" + str(apt_backup))
            if git_items:
                print("Git 私有备份：" + str(git_backup))

    def test(self):
        if os.geteuid() == 0:
            ensure_packages(["curl", "ca-certificates"])
        config = self.load()
        url = ask("测试 HTTPS 网址", "https://example.com")
        print(json.dumps(https_test(url, validate_proxy_config(config)), ensure_ascii=False, indent=2))

    def remove(self):
        print("这只删除本工具为该用户生成的代理配置；不会改变已有父终端或已启动进程。")
        print("已启用的终端请先运行 netpilot_proxy_off。")
        if not confirm("继续删除本用户当前配置和函数加载块？"):
            return
        self.set_apt(False)
        target = pathlib.Path(self.account.pw_dir) / ".bashrc"
        with as_operator():
            if target.exists():
                text = target.read_text(encoding="utf-8")
                updated = self.bashrc_without_block(text)
                if updated != text:
                    atomic_write(self.directory / ("bashrc.before-remove-" + timestamp()), text)
                    atomic_write(target, updated, 0o644)
            for path in (self.config_file, self.shell_file):
                if path.is_symlink():
                    raise UserError("拒绝删除符号链接代理配置。")
                if path.exists():
                    path.unlink()
        print("当前配置已删除；历史私有备份仍保留在 ~/.config/netpilot，请按需清理。")

    def run_command(self, command):
        if command and command[0] == "--":
            command = command[1:]
        if not command:
            raise UserError("用法：./network_setup.sh proxy-run -- curl -I https://example.com")
        config = self.load()
        env = dict(os.environ)
        env.update(proxy_environment(config))
        env["HOME"] = self.account.pw_dir
        env["USER"] = self.account.pw_name
        env["LOGNAME"] = self.account.pw_name
        def drop():
            os.initgroups(self.account.pw_name, self.account.pw_gid)
            os.setgid(self.account.pw_gid)
            os.setuid(self.account.pw_uid)
        preexec = drop if os.geteuid() == 0 and self.account.pw_uid != 0 else None
        try:
            return subprocess.call(command, env=env, preexec_fn=preexec)
        except FileNotFoundError:
            raise UserError("要执行的程序不存在：" + command[0])

